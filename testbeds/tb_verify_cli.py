"""S1.5: pch-verify offline CLI acceptance (DeepSeek plan 1.4):
- rejects a one-byte signature change; rejects a trailer edited after signing;
- accepts a clean receipt moved to "another machine" (a fresh folder holding
  only the receipt, the .sig and the public key; run from that folder);
- rejects wrong key, revoked key, missing/garbled sidecar.
Keys are generated by pch-keygen into a temp folder outside the repo.
Designed by: CloudAtlas. Built by: Cortana."""
import copy
import json
import os
import shutil
import subprocess
import sys
import tempfile

import pch_testlib
import stepstream

TOOLS = os.path.abspath(os.path.join(pch_testlib.HARNESS_DIR, "..", "tools"))
c = pch_testlib.Checks()
if not os.path.isfile(os.path.join(TOOLS, "pch_verify.py")):
    print("  [FAIL] pch-verify not present (pch/tools/pch_verify.py)")
    sys.exit(1)


def run(tool, *args, cwd=None):
    p = subprocess.run([sys.executable, os.path.join(TOOLS, tool), *args], cwd=cwd,
                       capture_output=True, text=True, timeout=120)
    return p.returncode, (p.stdout + p.stderr).strip()


src = stepstream.load_stream(os.path.join(pch_testlib.HARNESS_DIR, "stream_greedy.jsonl"))
body = [{k: v for k, v in r.items() if k != "chain"} for r in src if r["kind"] != "trailer"]
with tempfile.TemporaryDirectory(prefix="pch-cli-") as tmp:
    signer, other = os.path.join(tmp, "signer"), os.path.join(tmp, "machine-b")
    os.makedirs(other)
    rc, out = run("pch_keygen.py", "--out-dir", signer, "--name", "test-a")
    c("pch-keygen makes a key pair", rc == 0, out)
    c("pch-keygen prints no key material", "PRIVATE" not in out and "BEGIN" not in out)
    run("pch_keygen.py", "--out-dir", signer, "--name", "test-b")
    log = os.path.join(signer, "receipt.jsonl")
    stepstream.save_stream(stepstream.close(copy.deepcopy(body)), log)
    rc, out = run("pch_sign.py", log, os.path.join(signer, "test-a.key"))
    c("pch-sign signs a closed receipt", rc == 0, out)
    for n in ("receipt.jsonl", "receipt.jsonl.sig", "test-a.pub"):
        shutil.copy(os.path.join(signer, n), other)
    c("machine B holds no private key", not any(n.endswith(".key") for n in os.listdir(other)))
    rc, out = run("pch_verify.py", "receipt.jsonl", "test-a.pub", cwd=other)
    c("accepts clean receipt on machine B with only the public key", rc == 0, out)

    def tampered(name, mutate_log=None, mutate_sig=None, key="test-a.pub", extra=()):
        d = os.path.join(tmp, name.replace(" ", "_"))
        shutil.copytree(other, d)
        if mutate_log:
            recs = stepstream.load_stream(os.path.join(d, "receipt.jsonl"))
            mutate_log(recs)
            stepstream.save_stream(recs, os.path.join(d, "receipt.jsonl"))
        if mutate_sig:
            p = os.path.join(d, "receipt.jsonl.sig")
            with open(p) as f:
                s = f.read()
            with open(p, "w") as f:
                f.write(mutate_sig(s))
        if key != "test-a.pub":
            shutil.copy(os.path.join(signer, key), d)
        rc, out = run("pch_verify.py", "receipt.jsonl", key, *extra, cwd=d)
        c(f"rejects {name}", rc == 1, out)

    def flip_sig(s):
        d = json.loads(s)
        d["sig"] = ("1" if d["sig"][10] == "0" else "0").join([d["sig"][:10], d["sig"][11:]])
        return json.dumps(d)
    tampered("one-byte signature change", mutate_sig=flip_sig)

    def edit_trailer(recs):
        recs[-1]["steps"] += 1
    tampered("trailer edited after signing", mutate_log=edit_trailer)

    def rechain_trailer(recs):  # forger also fixes the trailer's chain link
        recs[-1]["steps"] += 1
        recs[-1]["chain"] = stepstream.chain_next(recs[-2]["chain"], recs[-1])
    tampered("trailer edited and re-chained after signing", mutate_log=rechain_trailer)

    def rehash_all(recs):  # bed 02 case 3: full re-hash forgery
        recs[3]["token"] = (recs[3]["token"] + 1) % 512
        b = [{k: v for k, v in r.items() if k != "chain"} for r in recs[:-1]]
        recs[:] = stepstream.close(b)
    tampered("full re-hash forgery", mutate_log=rehash_all)
    tampered("wrong public key", key="test-b.pub")
    tampered("garbled sidecar", mutate_sig=lambda s: s[:-5])
    tampered("sidecar with duplicate key", mutate_sig=lambda s: s.rstrip()[:-1] + ',"alg":"ed25519"}')
    kid = json.loads(open(os.path.join(other, "receipt.jsonl.sig")).read())["key_id"]
    with open(os.path.join(other, "revoked.json"), "w") as f:
        json.dump({"format": "pch-revocations/1",
                   "revoked": [{"key_id": kid, "revoked_at": "2026-10-23", "reason": "test"}]}, f)
    tampered("revoked key", extra=("--revoked", "revoked.json"))
    os.remove(os.path.join(other, "receipt.jsonl.sig"))
    rc, out = run("pch_verify.py", "receipt.jsonl", "test-a.pub", cwd=other)
    c("rejects missing sidecar", rc == 1, out)
c.finish("PCH-VERIFY OFFLINE CLI (S1.5)")
